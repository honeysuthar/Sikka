export const getDifficultyLabel = (difficulty: TaskDifficulty): string => {
  const map = { easy: 'Easy', medium: 'Medium', hard: 'Hard' };
  return map[difficulty];
};

export const getCategoryLabel = (category: TaskCategory): string => {
  const map: Record<TaskCategory, string> = {
    daily: 'Daily',
    weekly: 'Weekly',
    challenge: 'Challenge',
    social: 'Social',
    learning: 'Learning',
    fitness: 'Fitness',
  };
  return map[category];
};
